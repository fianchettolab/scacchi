// swift-tools-version: 6.0

import Foundation
import PackageDescription

// The release whose XCFramework this package downloads; written by release.sh.
let release = (version: "0.1.0", checksum: "32e37a9ed8fb87722078f1e97b9fbb339a22266ec6481c66733c5fcedb166307")

// A local build (build-xcframework.sh) wins over the release, so changes to the bridge
// show up in a checkout used as a local package override.
let localFramework = "build/ScacchiFFI.xcframework"
let hasLocalBuild = FileManager.default.fileExists(atPath: "\(Context.packageDirectory)/\(localFramework)")

let ffi: Target = hasLocalBuild || release.version.isEmpty
    ? .binaryTarget(name: "ScacchiFFI", path: localFramework)
    : .binaryTarget(
        name: "ScacchiFFI",
        url: "https://github.com/fianchettolab/scacchi/releases/download/\(release.version)/ScacchiFFI.xcframework.zip",
        checksum: release.checksum
    )

let package = Package(
    name: "Scacchi",
    platforms: [.iOS(.v17), .macOS(.v14)],
    products: [
        .library(name: "Scacchi", targets: ["Scacchi"]),
    ],
    targets: [
        ffi,
        // The UniFFI-generated bindings, regenerated by build-xcframework.sh.
        .target(name: "Scacchi", dependencies: ["ScacchiFFI"]),
        .testTarget(name: "ScacchiTests", dependencies: ["Scacchi"]),
    ]
)
